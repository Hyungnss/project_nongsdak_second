-- ── API 키 ───────────────────────────────────────────────────────────────────
CREATE TABLE TBL_API_KEY (
    KEY_NO          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_NO         BIGINT        NOT NULL REFERENCES TBL_USER (USER_NO) ON DELETE CASCADE,
    NAME            VARCHAR(40)   NOT NULL,
    KEY_PREFIX      VARCHAR(12)   NOT NULL,
    KEY_HASH        VARCHAR(64)   NOT NULL,
    PLAN            VARCHAR(20)   NOT NULL DEFAULT 'free',
    CREATED_AT      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    LAST_USED_AT    TIMESTAMPTZ,
    REVOKED_AT      TIMESTAMPTZ,
    CONSTRAINT UX_API_KEY_HASH UNIQUE (KEY_HASH)
);

-- 회원의 '살아 있는 키' 목록 · 개수 (발급 한도 확인)
CREATE INDEX IX_API_KEY_USER ON TBL_API_KEY (USER_NO) WHERE REVOKED_AT IS NULL;

COMMENT ON TABLE  TBL_API_KEY              IS '공개 API(/api/v1) 키. 회원만 발급받는다';
COMMENT ON COLUMN TBL_API_KEY.NAME         IS '회원이 붙인 이름 (예: 내 노트북)';
COMMENT ON COLUMN TBL_API_KEY.KEY_PREFIX   IS '키 앞 12자 (nsk_ + 8자). 화면에서 어느 키인지 알아보는 용도';
COMMENT ON COLUMN TBL_API_KEY.KEY_HASH     IS '키 원문의 SHA-256. 원문은 발급할 때 한 번만 보여 주고 저장하지 않는다';
COMMENT ON COLUMN TBL_API_KEY.PLAN         IS '요금제 — 지금은 free 하나. 한도는 backend/api_v1.py 의 PLANS';
COMMENT ON COLUMN TBL_API_KEY.LAST_USED_AT IS '마지막 사용 시각. 매 요청이 아니라 1분에 한 번만 갱신한다';
COMMENT ON COLUMN TBL_API_KEY.REVOKED_AT   IS '폐기 시각. NULL 이면 사용 가능. 행은 지우지 않는다 (사용량 기록이 이 키를 가리킨다)';


-- ── 하루 사용량 ──────────────────────────────────────────────────────────────
-- 요청마다 한 줄을 쌓지 않고 (날짜 · 키 · 엔드포인트 · 상태) 마다 합계를 누적한다.
-- 호출 수 · 오류율 · 평균/최대 응답 시간 · 하루 한도 계산이 모두 이 표 하나로 된다.
CREATE TABLE TBL_API_USAGE_DAILY (
    USAGE_DATE      DATE          NOT NULL,
    KEY_NO          BIGINT        NOT NULL REFERENCES TBL_API_KEY (KEY_NO) ON DELETE CASCADE,
    ENDPOINT        VARCHAR(60)   NOT NULL,
    STATUS_CLASS    CHAR(3)       NOT NULL,
    CALLS           INTEGER       NOT NULL DEFAULT 0,
    TOTAL_MS        BIGINT        NOT NULL DEFAULT 0,
    MAX_MS          INTEGER       NOT NULL DEFAULT 0,
    CONSTRAINT PK_API_USAGE_DAILY PRIMARY KEY (USAGE_DATE, KEY_NO, ENDPOINT, STATUS_CLASS),
    CONSTRAINT CK_API_USAGE_STATUS CHECK (STATUS_CLASS IN ('2xx', '3xx', '4xx', '5xx'))
);

-- 회원 화면의 '최근 30일' · 키별 오늘 합계
CREATE INDEX IX_API_USAGE_KEY_DATE ON TBL_API_USAGE_DAILY (KEY_NO, USAGE_DATE);

COMMENT ON TABLE  TBL_API_USAGE_DAILY              IS '공개 API 하루 사용량 (한국 날짜 기준 합계)';
COMMENT ON COLUMN TBL_API_USAGE_DAILY.ENDPOINT     IS '경로 틀 (예: /prices/history). 실제 쿼리 문자열은 남기지 않는다';
COMMENT ON COLUMN TBL_API_USAGE_DAILY.STATUS_CLASS IS '응답 상태 묶음 2xx · 4xx · 5xx';
COMMENT ON COLUMN TBL_API_USAGE_DAILY.TOTAL_MS     IS '응답 시간 합 (ms). 평균 = TOTAL_MS / CALLS';
