-- 원칙: 모든 특성 행에 AVAILABLE_AT(이 값을 알 수 있게 된 시각)을 둔다.
--   모델 학습 데이터를 만들 때 'AVAILABLE_AT <= 예측 시점' 인 값만 쓰면 미래 정보가 섞이지 않는다.
--   매일 수집으로 처음 본 행은 실제로 받은 시각, 과거분(백필)은 보수적인 규칙으로 정한다 (각 표 주석).
