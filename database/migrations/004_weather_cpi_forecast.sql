-- ── 수집 기록 (출처 공통) ───────────────────────────────────────────────────
CREATE TABLE TBL_INGEST_LOG (
    LOG_NO          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SOURCE          VARCHAR(20)   NOT NULL,
    TARGET          VARCHAR(100)  NOT NULL,
    STATUS          VARCHAR(20)   NOT NULL,
    ROWS_FETCHED    INTEGER       NOT NULL DEFAULT 0,
    ROWS_UPSERTED   INTEGER       NOT NULL DEFAULT 0,
    MESSAGE         VARCHAR(500),
    FETCHED_AT      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT CK_INGEST_LOG_STATUS CHECK (STATUS IN ('OK', 'NO_DATA', 'ERROR'))
);
CREATE INDEX IX_INGEST_LOG_SOURCE ON TBL_INGEST_LOG (SOURCE, FETCHED_AT);

COMMENT ON TABLE  TBL_INGEST_LOG        IS '특성 데이터 수집 기록 (weather · cpi · forecast). 스케줄러의 따라잡기 · 점검이 본다';
COMMENT ON COLUMN TBL_INGEST_LOG.SOURCE IS 'weather · cpi · forecast';
COMMENT ON COLUMN TBL_INGEST_LOG.TARGET IS '무엇을 받았나 (예: 108 2026-11-01~2026-11-17 · 901Y010 · 202611190600 ta)';


-- ── 관측소 ──────────────────────────────────────────────────────────────────
CREATE TABLE TBL_WEATHER_STATION (
    STN_ID          INTEGER       PRIMARY KEY,
    STN_NAME        VARCHAR(20)   NOT NULL,
    SIDO            VARCHAR(10)   NOT NULL,
    FIRST_DATE      DATE,
    LAST_DATE       DATE,
    UPDATED_AT      TIMESTAMPTZ   NOT NULL DEFAULT now()
);

COMMENT ON TABLE  TBL_WEATHER_STATION      IS '기상청 ASOS(종관) 관측소. 2026-11-17 기준 운영 중인 97곳 (collector/weather.py STATIONS)';
COMMENT ON COLUMN TBL_WEATHER_STATION.SIDO IS '시도 (관측소 이름으로 정함). 시도별 평균 날씨를 만들 때 쓴다';


-- ── 관측 날씨 (일) ──────────────────────────────────────────────────────────
-- 기상청 응답의 62개 항목 중 농산물과 관련 있는 것만 둔다. 원문은 보관하지 않는다 —
-- 기상청이 과거 관측을 모두 갖고 있어 언제든 다시 받을 수 있다 (예보와 다르다).
CREATE TABLE TBL_WEATHER_DAILY (
    OBS_DATE        DATE          NOT NULL,
    STN_ID          INTEGER       NOT NULL REFERENCES TBL_WEATHER_STATION (STN_ID),
    AVG_TA          NUMERIC(5, 1),
    MIN_TA          NUMERIC(5, 1),
    MAX_TA          NUMERIC(5, 1),
    SUM_RN          NUMERIC(6, 1),
    AVG_RHM         NUMERIC(5, 1),
    MIN_RHM         NUMERIC(5, 1),
    SUM_SS_HR       NUMERIC(5, 1),
    SUM_GSR         NUMERIC(7, 2),
    AVG_WS          NUMERIC(5, 1),
    MAX_WS          NUMERIC(5, 1),
    DD_MES          NUMERIC(6, 1),
    AVG_TS          NUMERIC(5, 1),
    MIN_TG          NUMERIC(5, 1),
    AVAILABLE_AT    TIMESTAMPTZ   NOT NULL,
    FETCHED_AT      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT PK_WEATHER_DAILY PRIMARY KEY (OBS_DATE, STN_ID),
    CONSTRAINT CK_WEATHER_TA CHECK (MIN_TA IS NULL OR MIN_TA BETWEEN -50 AND 50)
);
CREATE INDEX IX_WEATHER_DAILY_STN ON TBL_WEATHER_DAILY (STN_ID, OBS_DATE);

COMMENT ON TABLE  TBL_WEATHER_DAILY              IS '기상청 ASOS 일자료 (관측소 × 날짜)';
COMMENT ON COLUMN TBL_WEATHER_DAILY.AVG_TA       IS '평균기온 ℃ (avgTa)';
COMMENT ON COLUMN TBL_WEATHER_DAILY.MIN_TA       IS '최저기온 ℃ (minTa)';
COMMENT ON COLUMN TBL_WEATHER_DAILY.MAX_TA       IS '최고기온 ℃ (maxTa)';
COMMENT ON COLUMN TBL_WEATHER_DAILY.SUM_RN       IS '일강수량 mm (sumRn). 기상청은 비가 안 온 날 빈 값을 준다 — 0 으로 넣는다';
COMMENT ON COLUMN TBL_WEATHER_DAILY.AVG_RHM      IS '평균 상대습도 % (avgRhm)';
COMMENT ON COLUMN TBL_WEATHER_DAILY.MIN_RHM      IS '최소 상대습도 % (minRhm)';
COMMENT ON COLUMN TBL_WEATHER_DAILY.SUM_SS_HR    IS '합계 일조시간 hr (sumSsHr)';
COMMENT ON COLUMN TBL_WEATHER_DAILY.SUM_GSR      IS '합계 일사량 MJ/m2 (sumGsr)';
COMMENT ON COLUMN TBL_WEATHER_DAILY.AVG_WS       IS '평균 풍속 m/s (avgWs)';
COMMENT ON COLUMN TBL_WEATHER_DAILY.MAX_WS       IS '최대 풍속 m/s (maxWs)';
COMMENT ON COLUMN TBL_WEATHER_DAILY.DD_MES       IS '일 최심적설 cm (ddMes)';
COMMENT ON COLUMN TBL_WEATHER_DAILY.AVG_TS       IS '평균 지면온도 ℃ (avgTs)';
COMMENT ON COLUMN TBL_WEATHER_DAILY.MIN_TG       IS '최저 초상온도 ℃ (minTg) — 서리 판단';
COMMENT ON COLUMN TBL_WEATHER_DAILY.AVAILABLE_AT IS '알 수 있게 된 시각. 매일 수집은 처음 받은 시각, 백필은 관측일 다음 날 11:00 KST (일자료는 다음 날 오전에 나온다)';


-- ── 소비자물가 (월) ─────────────────────────────────────────────────────────
CREATE TABLE TBL_CPI_MONTHLY (
    PERIOD          CHAR(6)       NOT NULL,
    STAT_CODE       VARCHAR(10)   NOT NULL,
    ITEM_CODE       VARCHAR(10)   NOT NULL,
    ITEM_NAME       VARCHAR(40)   NOT NULL,
    VALUE           NUMERIC(10, 3) NOT NULL,
    UNIT            VARCHAR(20),
    AVAILABLE_AT    TIMESTAMPTZ   NOT NULL,
    FETCHED_AT      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT PK_CPI_MONTHLY PRIMARY KEY (PERIOD, STAT_CODE, ITEM_CODE)
);

COMMENT ON TABLE  TBL_CPI_MONTHLY              IS '한국은행 ECOS 소비자물가지수 (월). 901Y010 특수분류 — 농축수산물 · 채소 · 과실 등';
COMMENT ON COLUMN TBL_CPI_MONTHLY.PERIOD       IS '기준월 YYYYMM';
COMMENT ON COLUMN TBL_CPI_MONTHLY.AVAILABLE_AT IS '알 수 있게 된 시각. 매일 수집이 처음 본 시각, 백필은 다음 달 10일 00:00 KST (통계청 발표는 보통 다음 달 초)';


-- ── 중기예보 보관 ───────────────────────────────────────────────────────────
-- 기상청은 최근 24시간 발표분만 준다 — 지금 쌓지 않으면 다시 구할 수 없다. 그래서 원문도 남긴다.
CREATE TABLE TBL_FCST_RAW (
    TM_FC           TIMESTAMPTZ   NOT NULL,
    KIND            VARCHAR(10)   NOT NULL,
    REG_ID          VARCHAR(10)   NOT NULL,
    BODY            JSONB         NOT NULL,
    FETCHED_AT      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT PK_FCST_RAW PRIMARY KEY (TM_FC, KIND, REG_ID),
    CONSTRAINT CK_FCST_RAW_KIND CHECK (KIND IN ('ta', 'land'))
);

CREATE TABLE TBL_FCST_MID_TA (
    TM_FC           TIMESTAMPTZ   NOT NULL,
    REG_ID          VARCHAR(10)   NOT NULL,
    TARGET_DATE     DATE          NOT NULL,
    TA_MIN          NUMERIC(5, 1),
    TA_MAX          NUMERIC(5, 1),
    CONSTRAINT PK_FCST_MID_TA PRIMARY KEY (TM_FC, REG_ID, TARGET_DATE)
);

CREATE TABLE TBL_FCST_MID_LAND (
    TM_FC           TIMESTAMPTZ   NOT NULL,
    REG_ID          VARCHAR(10)   NOT NULL,
    TARGET_DATE     DATE          NOT NULL,
    RN_ST_AM        SMALLINT,
    RN_ST_PM        SMALLINT,
    WF_AM           VARCHAR(20),
    WF_PM           VARCHAR(20),
    CONSTRAINT PK_FCST_MID_LAND PRIMARY KEY (TM_FC, REG_ID, TARGET_DATE)
);

COMMENT ON TABLE  TBL_FCST_RAW             IS '기상청 중기예보 원문 (발표 × 종류 × 구역). 최근 24시간분만 받을 수 있어 그대로 보관한다';
COMMENT ON TABLE  TBL_FCST_MID_TA          IS '중기기온 예보 정리본. TM_FC(발표 시각)가 곧 AVAILABLE_AT 이다';
COMMENT ON TABLE  TBL_FCST_MID_LAND        IS '중기육상 예보 정리본 (강수확률 % · 하늘 상태). 8~10일 뒤는 오전 · 오후 구분 없이 같은 값';
COMMENT ON COLUMN TBL_FCST_MID_TA.TM_FC     IS '발표 시각 (06:00 · 18:00 KST)';
COMMENT ON COLUMN TBL_FCST_MID_TA.TARGET_DATE IS '예보 대상일 (발표일 + 3~10일)';
